import { spawn } from 'node:child_process';
import path from 'node:path';
import fs from 'node:fs';
const root=path.resolve(new URL('..',import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1'));
const project=process.argv[2];
const cwd=project==='rpg-rewards-paul'?root:path.join(root,'.integration-work',project==='between-turns-paul'?'between-turns':'rpg-bingo');
if(!['between-turns-paul','rpg-rewards-paul','rpg-bingo-paul'].includes(project))throw Error('Unknown deployment target.');
const only=process.argv[3]||'functions';
const appdata=path.join(root,'.firebase-config','deploy-appdata');fs.mkdirSync(appdata,{recursive:true});
const child=spawn(process.execPath,[path.join(root,'node_modules/firebase-tools/lib/bin/firebase.js'),'deploy','--project',project,'--only',only,'--non-interactive'],{cwd,stdio:'inherit',env:{...process.env,XDG_CONFIG_HOME:path.join(root,'.firebase-config'),APPDATA:appdata,NODE_USE_SYSTEM_CA:'1'}});
child.on('exit',code=>process.exit(code??1));
process.on('SIGINT',()=>child.kill('SIGINT'));
